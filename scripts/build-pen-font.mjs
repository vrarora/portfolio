/**
 * Builds the pen font for the case-study board from EMS Allure, a single-line
 * script face (SIL Open Font License). Each glyph becomes a list of polylines
 * in font units, y up, baseline at 0. Adds a matching rupee sign, which the
 * face does not include.
 *
 * Run: node scripts/build-pen-font.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "scripts/fonts/EMSAllure.svg";
const OUT = "src/components/v3/board/pen/allure.ts";

const svg = readFileSync(SOURCE, "utf8");
const defaultAdvance = Number(svg.match(/<font [^>]*horiz-adv-x="([\d.]+)"/)[1]);

const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&amp;/g, "&")
    .replace(/&apos;/g, "'")
    .replace(/&quot;/g, '"');

/** Parses M, L and C commands. Cubics are sampled into eight points. */
function parse(d) {
  const tokens = d.match(/[MLC]|-?[\d.]+(?:e-?\d+)?/g) ?? [];
  const strokes = [];
  let stroke = null;
  let cmd = null;
  let i = 0;
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    if (/[MLC]/.test(tokens[i])) cmd = tokens[i++];
    if (cmd === "M") {
      stroke = [[num(), num()]];
      strokes.push(stroke);
      cmd = "L";
    } else if (cmd === "L") {
      stroke.push([num(), num()]);
    } else if (cmd === "C") {
      const p0 = stroke[stroke.length - 1];
      const p1 = [num(), num()];
      const p2 = [num(), num()];
      const p3 = [num(), num()];
      for (let s = 1; s <= 8; s++) {
        const t = s / 8;
        const u = 1 - t;
        const b = (a0, a1, a2, a3) => u * u * u * a0 + 3 * u * u * t * a1 + 3 * u * t * t * a2 + t * t * t * a3;
        stroke.push([b(p0[0], p1[0], p2[0], p3[0]), b(p0[1], p1[1], p2[1], p3[1])]);
      }
    } else {
      i++;
    }
  }
  return strokes;
}

const glyphs = {};
for (const match of svg.matchAll(/<glyph ([^>]*)\/>/g)) {
  const attrs = match[1];
  const unicode = attrs.match(/unicode="([^"]*)"/);
  if (!unicode) continue;
  const ch = decode(unicode[1]);
  const code = ch.codePointAt(0);
  if (code < 32 || code > 126) continue;
  const adv = Number(attrs.match(/horiz-adv-x="([\d.]+)"/)?.[1] ?? defaultAdvance);
  const d = attrs.match(/ d="([^"]*)"/)?.[1] ?? "";
  glyphs[ch] = { adv, strokes: parse(d) };
}

// Rupee sign drawn upright, then slanted to match the script's lean

const SLANT = 0.25;
const rupee = [
  [[60, 500], [360, 500]],
  [[60, 415], [360, 415]],
  [[140, 500], [230, 495], [282, 465], [288, 422], [252, 386], [190, 362], [110, 352]],
  [[110, 352], [320, 0]],
].map((stroke) => stroke.map(([x, y]) => [x + y * SLANT, y]));
glyphs["₹"] = { adv: 470, strokes: rupee };

const round = (n) => Math.round(n * 10) / 10;
const body = Object.entries(glyphs)
  .map(([ch, g]) => `  ${JSON.stringify(ch)}: [${g.adv}, ${JSON.stringify(g.strokes.map((s) => s.flat().map(round)))}],`)
  .join("\n");

writeFileSync(
  OUT,
  `/**
 * Generated by scripts/build-pen-font.mjs. Do not edit by hand.
 *
 * Glyphs from EMS Allure by Sheldon B. Michaels, a single-line derivative of
 * Allura by Rob Leuschke (TypeSETit). SIL Open Font License 1.1.
 * Each entry is [advance, strokes], where a stroke is a flat x,y list in
 * font units (1000 per em, y up, baseline 0).
 */
export const UNITS_PER_EM = 1000;

export const GLYPHS: Record<string, readonly [number, readonly (readonly number[])[]]> = {
${body}
};
`,
);

console.log(`Wrote ${Object.keys(glyphs).length} glyphs to ${OUT}`);
